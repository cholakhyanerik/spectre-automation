fn check_terminal_state(db_path: &Path) -> bool {
    if db_path.exists() {
        println!("💾 Найдена существующая база exchanges.db: {}", db_path.display());
        println!("🔥 ТЕСТ: Замер производительности при восстановлении сохраненного стейта.");
        true
    } else {
        println!(
            "ℹ️  Файл exchanges.db не найден ({}). Тест начнется с чистого экрана (стейт пуст).",
            db_path.display()
        );
        false
    }
}

/// Говорит вслух, что стенд занят живым терминалом. `true` — мерить нельзя.
///
/// Это тот случай, где остановка лучше молчаливого продолжения. При коротком
/// замере харнесс предупреждает и мерит дальше — там числа хотя бы про нужный
/// процесс. Здесь не так: наш запуск передаст управление уже работающему
/// экземпляру и выйдет, а замер уедет на ЧУЖОЙ процесс — возможно, другой
/// сборки, возможно, прогретой час назад. В конце прогона харнесс закрыл бы его
/// по совпадению имени вместе с несохранённым.
fn stand_is_busy(db_path: &Path) -> bool {
    match instance::probe(db_path) {
        instance::Stand::Free => false,
        instance::Stand::Busy(info) => {
            eprintln!("❌ Терминал уже запущен — замерить эту сборку нельзя.");
            eprintln!(
                "   Замок {} держит живой экземпляр.",
                instance::lock_path(db_path).display()
            );
            match info {
                Some(instance::InstanceInfo { pid, http_port: Some(port) }) => {
                    eprintln!("   Он назвался: PID {pid}, HTTP-порт {port}.");
                }
                Some(instance::InstanceInfo { pid, http_port: None }) => {
                    eprintln!("   Он назвался: PID {pid} (порт ещё не опубликован — экземпляр запускается).");
                }
                // Замок занят, а сказать о себе некому: запись могла не успеть
                // появиться или быть стёрта. На решение это не влияет.
                None => eprintln!("   Кто именно — сказать нечем: instance.json отсутствует или испорчен."),
            }
            eprintln!("   Терминал одноэкземплярный: наш запуск не станет вторым процессом — он");
            eprintln!("   передаст запрос уже работающему и выйдет за доли секунды с кодом 0.");
            eprintln!("   Замер после этого пошёл бы по ЧУЖОМУ процессу (совпадение имени), а в");
            eprintln!("   конце прогона харнесс закрыл бы его вместе с несохранённым.");
            eprintln!("   Закройте терминал и запустите замер заново.");
            true
        }
        instance::Stand::Unknown(why) => {
            // Не «свободно», а «не смогли посмотреть». Мерить не запрещаем —
            // сломанная проверка не должна становиться причиной, по которой
            // замер не идёт, — но и молчать нельзя: если экземпляр всё-таки
            // работал, числа будут про него.
            eprintln!("⚠️  Не удалось проверить, не запущен ли терминал: {why}.");
            eprintln!("    Замер продолжается. Если терминал сейчас открыт, закройте его: числа");
            eprintln!("    получатся про ЕГО процесс, а не про запускаемую сборку.");
            false
        }
    }
}

/// Говорит вслух, что запущенный процесс не дожил до замера.
///
/// Отдельного «времени смерти» здесь нет намеренно: `try_wait` отвечает на
/// вопрос «жив ли сейчас», а не «когда умер», и назвать точную секунду было бы
/// выдумкой. Поэтому в сообщении стоит момент ПРОВЕРКИ — величина, которую мы
/// действительно измерили.
fn warn_handover(app_path: &str, status: std::process::ExitStatus, checked_after: Duration) {
    eprintln!("❌ Запущенный процесс не дожил до замера: '{app_path}'.");
    eprintln!(
        "   Через {:.1} сек после запуска его уже не было в системе, код возврата: {}.",
        checked_after.as_secs_f32(),
        status.code().map_or_else(|| "неизвестен".to_string(), |c| c.to_string())
    );
    eprintln!("   Так выглядит передача запуска УЖЕ РАБОТАЮЩЕМУ экземпляру: терминал");
    eprintln!("   одноэкземплярный и выходит с кодом 0, то есть от удачного запуска это");
    eprintln!("   неотличимо ничем, кроме самой проверки. Так же выглядит и падение при");
    eprintln!("   старте. Мерить в обоих случаях нечего: наш процесс мёртв, а всё, что");
    eprintln!("   совпадает по имени, запустили не мы.");
    eprintln!("   Поэтому ничего по имени НЕ завершаем: это закрыло бы чужой терминал");
    eprintln!("   вместе с несохранённым. Если процессы приложения в системе остались,");
    eprintln!("   закройте их сами (диспетчер задач, Get-Process, ps).");
}

/// Сколько ждать от запуска, прежде чем спросить, наш ли процесс живёт.
///
/// Передача запуска живому экземпляру происходит в самом начале работы
/// терминала, до базы и до обновлений: замерено 06.09.2026 на этой машине —
/// 0,11 с. Две секунды дают почти двадцатикратный запас на холодный старт и
/// при этом не стоят ничего: сценарий ввода к моменту проверки идёт уже
/// около четырёх с половиной секунд, и ожидание возвращается сразу. Отдельная
/// константа нужна, чтобы проверка не зависела от длительности сценария —
/// укоротят сценарий, и запас исчезнет молча.
const HANDOVER_CHECK_AFTER: Duration = Duration::from_secs(2);

// Вспомогательная функция для извлечения имени файла из пути
fn extract_filename(path: &str) -> String {
    Path::new(path)
        .file_name()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_else(|| "unknown.exe".to_string())
}

/// Говорит вслух, что прогон короче выхода приложения на режим.
///
/// Отказываться мерить нельзя: маленькая длительность осмысленна, когда
/// проверяют сам харнесс. Но и промолчать нельзя — статистика посчитается и
/// напечатается как обычно (медиана, p95, вердикт «хуже / лучше»), только
/// относиться она будет к разгону приложения. Это худший исход из возможных
/// здесь: число есть, оно правдоподобно, и оно про другое.
fn warn_short_run(duration_secs: u64, settle_secs: u64) {
    if !config::is_short_run(duration_secs, settle_secs) {
        return;
    }
    eprintln!("⚠️  Замер короче выхода на режим: {} сек при пороге {} сек.", duration_secs, settle_secs);
    eprintln!("    Приложение всё это время ещё разгоняется, поэтому медиана, p95 и пик");
    eprintln!("    опишут ЗАПУСК, а не потребление, и сравнивать по ним сборки нельзя.");
    eprintln!("    Для сравнения задайте TEST_DURATION_SECS заведомо больше выхода на режим");
    eprintln!("    (от минуты, на практике — три). Порог меняется через SETTLE_SECS в .env,");
    eprintln!("    ноль его отключает.");
}

/// То же предупреждение одной строкой, рядом с готовыми числами.
///
/// Прогон печатает много, и к моменту, когда человек смотрит на таблицу,
/// предупреждение из начала уже уехало из окна терминала. А смотрят именно
/// на числа — оговорка обязана лежать там же, где они.
fn note_short_run(duration_secs: u64, settle_secs: u64) {
    if config::is_short_run(duration_secs, settle_secs) {
        eprintln!(
            "⚠️  Числа этого прогона сняты за {} сек — это ЗАПУСК приложения, а не \
             установившееся потребление (порог SETTLE_SECS = {} сек).",
            duration_secs, settle_secs
        );
    }
}

/// Какая сборка меряется на этом шаге прогона.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Which {
    /// Актуальная, `APP_PATH_NEW`. Её провал — единственный, что роняет прогон.
    New,
    /// Старая, `APP_PATH_OLD`. Её провал — предупреждение, а не ошибка.
    Old,
}

impl Which {
    /// Короткое имя сборки для сообщений о стенде.
    fn label(self) -> &'static str {
        match self {
            Which::New => "актуальная сборка",
            Which::Old => "старая сборка",
        }
    }
}

/// Что сказать, если замер изменил состояние стенда. `None` — говорить нечего.
///
/// Молчание здесь имеет ровно одно значение: состояние прочитано дважды и оно
/// одинаковое. Случай «прочитать не удалось» молчанием НЕ считается — иначе
/// сломавшаяся проверка выглядела бы как успешная, и человек унёс бы из прогона
/// уверенность, которой никто не проверял (Правило 6).
///
/// `restores` — вернётся ли стенд после этого замера (`RESTORE_STAND`). От него
/// зависит не факт, а вывод: схема сдвинута в обоих случаях, но при включённом
/// восстановлении следующая сборка её уже не увидит. Оставить один текст на оба
/// случая значило бы соврать ровно в ту сторону, в какую человек и без того
/// боится ошибиться.
fn schema_change_note(
    label: &str,
    before: &instance::Schema,
    after: &instance::Schema,
    restores: bool,
) -> Option<String> {
    let consequence = if restores {
        "\x20   Перед следующим замером стенд будет возвращён в снятое до прогона состояние\n\
         \x20   (RESTORE_STAND включён), поэтому на сравнение сборок это не повлияет."
    } else {
        "\x20   Следующая сборка стартует уже на ЭТОМ состоянии, и её числа будут про\n\
         \x20   другой стенд — в отчёте это выглядит обычной разницей сборок."
    };
    match before.differs_from(after) {
        Some(true) => Some(format!(
            "⚠️  Замер ({label}) изменил состояние стенда: было «{}», стало «{}».\n\
             \x20   Терминал накатывает миграции схемы при старте, а обратных не хранит.\n\
             {consequence}",
            before.describe(),
            after.describe()
        )),
        Some(false) => None,
        None => Some(format!(
            "⚠️  Сверить состояние стенда после замера ({label}) не удалось: было «{}», стало «{}».\n\
             \x20   Менялась ли схема за этот замер — неизвестно, а это не то же самое, что\n\
             \x20   «не менялась».",
            before.describe(),
            after.describe()
        )),
    }
}

/// Что сказать, если две сборки прогона стартовали на разных стендах.
///
/// Это и есть ответ на вопрос «сравнивали ли одинаковое», и отвечает на него
/// не догадка, а два факта, снятых до запусков. Сравниваются именно НАЧАЛЬНЫЕ
/// состояния: разойтись они могут не только от миграций первой сборки, но и от
/// чего угодно ещё, что случилось со стендом между замерами.
///
/// При нечитаемом состоянии молчит намеренно: об этом уже сказано строкой
/// «Состояние стенда перед замером», и повторять то же самое вторым
/// предупреждением — верный способ приучить не читать оба.
fn schema_gap_note(first: (&str, &instance::Schema), second: (&str, &instance::Schema)) -> Option<String> {
    if first.1.differs_from(second.1) != Some(true) {
        return None;
    }
    Some(format!(
        "⚠️  Сборки стартовали на РАЗНЫХ состояниях стенда — сравнивать их числа нельзя.\n\
         \x20   Перед замером ({}): {}\n\
         \x20   Перед замером ({}): {}\n\
         \x20   Обратных миграций терминал не хранит, поэтому вернуть стенд в прежнее\n\
         \x20   состояние сам харнесс не может. Разница в отчёте окажется разницей\n\
         \x20   СОСТОЯНИЙ, а не сборок: сколько окон восстановить, сколько подписок\n\
         \x20   открыть — решает стейт. Перемеряйте сборки на одинаковом стенде.",
        first.0,
        first.1.describe(),
        second.0,
        second.1.describe()
    ))
}

/// Опрашивает стенд после замера и говорит, если этот замер его изменил.
fn note_schema_after(label: &str, before: &instance::Schema, db_path: &Path, restores: bool) {
    if let Some(note) = schema_change_note(label, before, &instance::schema(db_path), restores) {
        eprintln!("{note}");
    }
}

/// Куда кладётся снимок стенда на время прогона.
///
/// Не в `reports/current`: тот очищается перед прогоном и целиком копируется в
/// архив, а восьмимегабайтная копия чужой базы в архиве замеров не нужна. И не
/// во временный каталог системы: если харнесс прервётся между замерами, стенд
/// останется в состоянии после первой сборки, и вернуть его руками человек
/// сможет только из этих файлов — значит лежать они должны там, где их найдут.
/// Каталог перезаписывается на каждом прогоне со снимком.
const STAND_SNAPSHOT_DIR: &str = "reports/stand-snapshot";

/// Снимает копию стенда перед прогоном — или объясняет, почему не снимает.
///
/// `None` означает «восстанавливать нечем», и дальше прогон идёт ровно так, как
/// шёл до появления флага: со сверкой состояний и предупреждением о расхождении.
/// Отказываться мерить из-за неснятого снимка нельзя — это превратило бы
/// вспомогательную удобность в третью причину, по которой замера нет.
fn take_stand_snapshot(cfg: &Config, steps: usize) -> Option<instance::Snapshot> {
    if !cfg.restore_stand {
        return None;
    }
    if steps < 2 {
        // Человек ЗАДАЛ восстановление и не задал вторую сборку. Промолчать
        // нельзя: он ждёт выравненного стенда, а выравнивать не между чем.
        println!("ℹ️  RESTORE_STAND включён, но сборка одна — стенд возвращать не перед чем.");
        return None;
    }
    // Снимок делается с ПОКОЯЩЕГОСЯ стенда. Под живым терминалом копия вышла бы
    // рваной: часть страниц из базы, часть из журнала, и вернули бы мы состояние,
    // которого не было ни до, ни после.
    if stand_is_busy(&cfg.db_path) {
        return None;
    }

    match instance::snapshot(&cfg.db_path, Path::new(STAND_SNAPSHOT_DIR)) {
        Ok(snap) => {
            println!(
                "🗄️  Снимок стенда снят ({} файлов в {}): {}",
                snap.captured(),
                snap.dir().display(),
                snap.schema().describe()
            );
            println!("   Перед вторым замером стенд будет возвращён в это состояние, чтобы обе");
            println!("   сборки стартовали одинаково. Это единственное место, где харнесс ПИШЕТ");
            println!("   в каталог данных приложения.");
            Some(snap)
        }
        Err(why) => {
            eprintln!("⚠️  Снимок стенда не снялся: {why}.");
            eprintln!("    Замер продолжается БЕЗ восстановления: сборкам достанутся разные");
            eprintln!("    состояния, и о расхождении харнесс скажет отдельно.");
            None
        }
    }
}

/// Возвращает стенд в состояние, снятое до прогона.
///
/// Проверка замка здесь обязательна и стоит именно перед записью: `probe`
/// делался до первого запуска, а с тех пор прошёл целый замер. Останься терминал
/// жив (не добился, открыт человеком) — восстановление писало бы в базу под
/// живым процессом, то есть не выравнивало бы стенд, а портило его, заодно
/// рискуя тем, что этот процесс успел не сохранить.
fn restore_stand(snap: &instance::Snapshot, db_path: &Path) {
    if stand_is_busy(db_path) {
        eprintln!("⚠️  Стенд не возвращён: терминал ещё жив, писать в базу под ним нельзя.");
        return;
    }
    match snap.restore() {
        Ok(instance::Restored::Confirmed) => {
            println!("🗄️  Стенд возвращён в снятое до прогона состояние: {}", snap.schema().describe());
        }
        Ok(instance::Restored::Unverified(now)) => {
            eprintln!("⚠️  Стенд возвращён, но подтвердить это состоянием не вышло:");
            eprintln!("    снимали «{}», сейчас читается «{}».", snap.schema().describe(), now.describe());
            eprintln!("    Одинаковый ли стенд достался сборкам — неизвестно, а это не то же");
            eprintln!("    самое, что «одинаковый».");
        }
        Err(why) => {
            eprintln!("❌ Стенд НЕ возвращён: {why}.");
            eprintln!("   Замер продолжается, но сборки мерятся на разных состояниях — сравнивать");
            eprintln!("   их числа нельзя. Копия стенда лежит в {}: вернуть её", STAND_SNAPSHOT_DIR);
            eprintln!("   можно руками, скопировав файлы обратно рядом с {}.", db_path.display());
        }
    }
}

/// Составляет очередь замеров на этот запуск харнесса.
///
/// Вынесено в чистую функцию, потому что ошибиться здесь можно молча и дорого.
/// Выпади отсюда актуальная сборка — прогон завершился бы «успешно», не измерив
/// ничего; переставься очередь не в ту сторону — числа поменялись бы местами
/// в пользу другой сборки, и отличить это по отчёту было бы нечем: колонки
/// в сравнительной таблице задаются не очередью, а `APP_PATH_NEW` / `_OLD`,
/// и стоят на своих местах при любом порядке замера.
///
/// Без старой сборки очередь ни на что не влияет: мерить всё равно нечего,
/// кроме актуальной, и `RUN_ORDER` в этом случае просто не при чём.
fn run_sequence(order: RunOrder, has_old: bool) -> Vec<Which> {
    if !has_old {
        return vec![Which::New];
    }
    match order {
        RunOrder::NewFirst => vec![Which::New, Which::Old],
        RunOrder::OldFirst => vec![Which::Old, Which::New],
    }
}

/// Говорит вслух, в какой очереди пойдут замеры и чем эта очередь стоит.
///
/// Порядок влияет на числа, а из отчёта он не виден ниоткуда, кроме этой
/// строки и поля `run_position` в JSON: первая сборка платит за холодный кэш
/// ФС и прогрев, вторая получает их даром.
fn announce_run_order(order: RunOrder, has_old: bool) {
    if !has_old {
        // Сравнивать не с чем. Но если человек ЗАДАЛ порядок и не задал старую
        // сборку, промолчать нельзя: он ждёт перестановки, а её не будет.
        if order != config::DEFAULT_RUN_ORDER {
            println!(
                "ℹ️  RUN_ORDER={} задан, но APP_PATH_OLD нет — переставлять нечего, меряем только актуальную.",
                order.as_str()
            );
        }
        return;
    }

    let (first, second) = match order {
        RunOrder::NewFirst => ("АКТУАЛЬНАЯ", "СТАРАЯ"),
        RunOrder::OldFirst => ("СТАРАЯ", "АКТУАЛЬНАЯ"),
    };
    println!("🔀 Очередь замера (RUN_ORDER={}): 1) {} → 2) {}.", order.as_str(), first, second);
    println!("   Первая сборка платит за холодный кэш ФС и прогрев, вторая получает их даром:");
    println!("   сильнее всего это видно на пике CPU и на первых секундах графика.");
}

/// Выполняет синхронный шаг прогона так, чтобы он НЕ занимал воркер Tokio.
///
/// Сценарий ввода спит блокирующим `std::thread::sleep` суммарно около 4,5 секунд
/// и переписать его на `tokio::time::sleep` нельзя: `enigo` синхронный. Прямой
/// вызов из async-функции занимал бы воркер рантайма целиком, и сходило бы это
/// с рук только по везению — потому что `#[tokio::main]` по умолчанию даёт
/// многопоточный рантайм и задача мониторинга уезжает на другой воркер. Переход
/// на `flavor = "current_thread"` (одна строка, выглядящая упрощением) превратил
/// бы это в 4,5 секунды без единого замера в начале КАЖДОГО прогона: ни ошибки
/// сборки, ни подсказки clippy, ни падения — график просто начался бы с пятой
/// секунды, а разгон приложения, самое интересное место замера, не попал бы в
/// отчёт вовсе. `spawn_blocking` уводит шаг в отдельный пул потоков и снимает
/// зависимость замера от устройства рантайма.
///
/// Тем же путём уходит завершение приложения: оно ждёт смерти процессов и
/// потому тоже блокирующее. Мерить в тот момент уже нечего, но образец,
/// который скопирует следующий рефакторинг, важнее сиюминутной безвредности.
///
/// Паника внутри шага не роняет прогон: сценарий важен, но замер важнее.
async fn run_blocking_step<F>(name: &str, step: F)
where
    F: FnOnce() + Send + 'static,
{
    if let Err(e) = tokio::task::spawn_blocking(step).await {
        eprintln!("⚠️  Шаг «{}» не отработал ({}). Прогон продолжается.", name, e);
    }
}

/// Запускает приложение, снимает метрики за `duration_secs`, затем гарантированно
/// завершает и «пожинает» (`wait`) процесс со всем деревом окон/модалок.
///
/// Возвращает `None`, если приложение не удалось запустить или мониторинг упал —
/// вызывающая сторона решает, критично это (актуальная версия) или можно
/// пропустить (старая версия для сравнения). Никаких паник и утечек процессов:
/// очистка выполняется в любом случае.
async fn run_single_test(
    step: &str,
    label: &str,
    app_path: &str,
    duration_secs: u64,
    match_processes: Vec<String>,
    run_position: u8,
    db_path: &Path,
) -> Option<monitor::TestResult> {
    let exe_name = extract_filename(app_path);
    println!("\n{} Запуск {} ({})...", step, label, exe_name);

    // Стенд проверяется перед КАЖДОЙ сборкой, а не один раз за прогон: между
    // двумя замерами терминал может остаться жив — не добился с прошлого шага
    // или его открыл человек, — и тогда вторая сборка «померяет» первую.
    if stand_is_busy(db_path) {
        return None;
    }

    let mut child = match runner::run_app(app_path) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("❌ Не удалось запустить приложение '{}': {}", app_path, e);
            return None;
        }
    };
    let pid = child.id();
    let launched_at = Instant::now();

    let monitor_handle = tokio::spawn(monitor::start_monitoring(
        pid,
        duration_secs,
        exe_name,
        match_processes.clone(),
        run_position,
    ));
    // Сценарий блокирующий — уводим его с воркера рантайма, иначе замер
    // начинается только после него (см. `run_blocking_step`).
    run_blocking_step("Сценарий UI", runner::execute_ui_scenario).await;

    // Проверка стенда стоит ДО запуска и потому видит не всё: замок мог быть
    // свободен, а запуск всё равно не стать нашим процессом (гонка, чужой
    // экземпляр на другом каталоге данных, падение при старте). Поэтому здесь
    // проверяется ФАКТ — жив ли тот процесс, который мы запустили, — а не
    // признак. Ожидание в норме возвращается сразу: сценарий уже дольше.
    sleep_until(launched_at + HANDOVER_CHECK_AFTER).await;
    if let Ok(Some(status)) = child.try_wait() {
        monitor_handle.abort();
        warn_handover(app_path, status, launched_at.elapsed());
        return None;
    }

    let result = match monitor_handle.await {
        Ok(r) => Some(r),
        Err(e) => {
            eprintln!("❌ Задача мониторинга завершилась с ошибкой: {}", e);
            None
        }
    };

    // Очистка выполняется ВСЕГДA, даже если мониторинг упал: сначала гасим
    // сам процесс и «пожинаем» его (иначе остаётся зомби), затем добиваем
    // дерево окон/модалок, чтобы осиротевшие окна не искажали следующий прогон.
    let _ = child.kill();
    let _ = child.wait();
    // Добивание ждёт смерти процессов и проверяет ФАКТ, а не код возврата
    // (Правило 6), то есть спит блокирующим sleep до полутора секунд. Мерить
    // в этот момент уже нечего, но занимать воркер рантайма всё равно незачем:
    // уводим шаг в отдельный пул тем же способом, что и сценарий ввода.
    run_blocking_step("Завершение приложения", move || {
        monitor::terminate_app(pid, &match_processes)
    })
    .await;

    result
}

#[tokio::main]
async fn main() {
    println!("====================================================");
    println!("🚀 Запуск Spectre-Automation: Сбор метрик десктоп GUI");
    println!("====================================================");

    // 1. Создаем папку current и history (current при этом будет очищена!)
    report::init_reports_dir();

    // 2. Загружаем конфигурацию
    let cfg = Config::load();
    println!("🖥️  Платформа: {}", config::platform_name());
    println!("ℹ️  Настроенная длительность тестов: {} сек", cfg.test_duration_secs);
    warn_short_run(cfg.test_duration_secs, cfg.settle_secs);

    // 3. Проверяем состояние БД
    check_terminal_state(&cfg.db_path);

    // --- ЗАМЕРЫ В ЗАДАННОЙ ОЧЕРЕДИ ---
    // Очередь решает `RUN_ORDER`, а не порядок операторов здесь: первая сборка
    // платит за холодный кэш ФС и прогрев, и это систематическая фора второй.
    let has_old = cfg.app_path_old.is_some();
    let sequence = run_sequence(cfg.run_order, has_old);
    let total = sequence.len();
    announce_run_order(cfg.run_order, has_old);

    // Снимок снимается ДО первого запуска: вернуть стенд можно только в то
    // состояние, которое видела первая сборка. `None` — восстановления не будет
    // (флаг выключен, сборка одна или снимок не снялся).
    let snapshot = take_stand_snapshot(&cfg, total);

    let mut result_new: Option<monitor::TestResult> = None;
    let mut result_old: Option<monitor::TestResult> = None;
    // Состояние стенда перед ПЕРВЫМ замером: с ним сверяется второй. Разошлись —
    // сборки мерились на разных стендах, и разница в отчёте про них, а не про код.
    let mut first_start: Option<(&str, instance::Schema)> = None;

    for (i, which) in sequence.iter().enumerate() {
        // Позиция замера уезжает в TestResult и дальше в архив: без неё через
        // месяцы не отличить сборку, мерившуюся на холодной машине, от второй.
        let position = (i + 1) as u8;
        let step = format!("[Шаг {}/{}]", position, total);
        let label = which.label();
        // Вернётся ли стенд ПОСЛЕ этого замера. На последнем шаге — нет, даже при
        // включённом флаге: снимок выравнивает сборки между собой, а не прибирает
        // за прогоном, и следующему прогону стенд достанется таким, каким его
        // оставила последняя сборка.
        let restored_after = snapshot.is_some() && i + 1 < total;

        // Стенд возвращается ПЕРЕД чтением состояния, а не после: печатается то,
        // на чём замер реально пойдёт. Перед первым замером возвращать не к чему —
        // снимок с него и снят.
        if i > 0
            && let Some(snap) = &snapshot
        {
            restore_stand(snap, &cfg.db_path);
        }

        // Стенд опрашивается ДО запуска и ПОСЛЕ убийства, а не по ходу замера:
        // база у терминала и у харнесса одна, и чтение во время прогона стало бы
        // конкуренцией за те же страницы. Оба опроса стоят вне цикла семплинга и
        // вместе стоят миллисекунды.
        let schema_before = instance::schema(&cfg.db_path);
        println!("🗄️  Состояние стенда перед замером ({label}): {}", schema_before.describe());
        if let Some((first_label, first_schema)) = &first_start
            && let Some(note) = schema_gap_note((first_label, first_schema), (label, &schema_before))
        {
            eprintln!("{note}");
        }

        match which {
            Which::New => {
                let measured = run_single_test(
                    &step,
                    "АКТУАЛЬНОЙ версии",
                    &cfg.app_path_new,
                    cfg.test_duration_secs,
                    cfg.match_processes.clone(),
                    position,
                    &cfg.db_path,
                )
                .await;
                note_schema_after(label, &schema_before, &cfg.db_path, restored_after);

                let Some(result) = measured else {
                    // Единственный провал, который роняет прогон, — и он роняет
                    // его в любой очереди, а не только когда идёт первым.
                    eprintln!("❌ Не удалось протестировать актуальную версию. Завершение работы.");
                    // При RUN_ORDER=old-first старая сборка к этому моменту уже
                    // измерена, и запись в истории для неё уже сделана. Уйти
                    // отсюда молча — значит выбросить готовый замер из-за чужого
                    // провала и оставить в истории строку без копии в архиве.
                    if result_old.is_some() {
                        report::archive_current_run();
                    }
                    return;
                };
                println!("✅ Тест актуальной версии завершен.");

                report::print_visual_report(&result);
                report::save_report_json("actual", &result);
                report::save_run_to_history(&result);
                result_new = Some(result);
            }
            Which::Old => {
                // `run_sequence` ставит сюда шаг только когда путь задан;
                // проверка оставлена, чтобы рассинхрон не превратился в панику.
                let Some(app_path_old) = cfg.app_path_old.as_deref() else {
                    continue;
                };
                let measured = run_single_test(
                    &step,
                    "СТАРОЙ версии",
                    app_path_old,
                    cfg.test_duration_secs,
                    cfg.match_processes.clone(),
                    position,
                    &cfg.db_path,
                )
                .await;
                note_schema_after(label, &schema_before, &cfg.db_path, restored_after);

                if let Some(result) = measured {
                    println!("✅ Тест старой версии завершен.");

                    report::print_visual_report(&result);
                    report::save_report_json("old", &result);
                    report::save_run_to_history(&result);
                    result_old = Some(result);
                }
            }
        }

        // Эталон для сверки — состояние перед ПЕРВЫМ замером, а не перед
        // предыдущим: вопрос в том, одинаковый ли стенд достался сборкам.
        if first_start.is_none() {
            first_start = Some((label, schema_before));
        }
    }

    // --- ОТЧЁТЫ ---
    if !has_old {
        println!("\n[Инфо] Старая версия не указана. Генерируем одиночный график...");
    } else if result_old.is_none() {
        eprintln!("⚠️  Старую версию протестировать не удалось — строим одиночный график актуальной.");
    }

    let compared = if let (Some(new), Some(old)) = (&result_new, &result_old) {
        report::print_comparison_report(new, old);
        if let Err(e) = report::generate_comparison_chart(new, old) {
            eprintln!("⚠️  Не удалось построить сравнительный график: {}", e);
        }
        true
    } else {
        false
    };

    if !compared
        && let Some(new) = &result_new
        && let Err(e) = report::generate_single_chart("actual", new)
    {
        eprintln!("⚠️  Не удалось построить график: {}", e);
    }

    // --- АРХИВАЦИЯ РЕЗУЛЬТАТОВ ---
    // Копируем все файлы текущего прогона в history/ с временными метками
    report::archive_current_run();

    note_short_run(cfg.test_duration_secs, cfg.settle_secs);

    println!("\n🎉 Тестирование успешно завершено! Отчеты сохранены в 'reports/'");
    println!("====================================================");
}

